def brief_content(**over) -> dict:
    base = {
        "video_objective": "Delight a child on their birthday with a gentle original song.",
        "target_audience": "Parents and children aged 3-8", "viewer_benefit": "A song they can sing along to.",
        "main_concept": "A morning garden celebration", "tone_and_style": "warm, playful", "planned_length_seconds": 20,
        "visual_direction": "bright illustrated hills", "audio_direction": "bells, pad, soft drums",
        "hook_and_opening": "Bells over a sunrise", "structure": "intro, verse, chorus, outro",
        "thumbnail_concept": "Big title over sunrise", "distinctive_elements": ["garden-morning story told in the lyrics"],
        "originality_requirements": ["no reused lines", "own melody"], "success_criteria": ["viewer retention past 15s"],
        "musical_plan": {"tempo_bpm": 104, "key": "G major", "mood": "bright", "instrumentation": ["bells", "pad", "bass", "drums"],
                         "vocal_delivery": "instrumental", "song_structure": ["intro", "verse", "chorus", "outro"]},
        "style_tags": ["garden", "sunrise"],
    }
    mp = over.pop("musical_plan", None)
    base.update(over)
    if mp:
        base["musical_plan"] = {**base["musical_plan"], **mp}
    return base


def make_video(db, agent, channel=BDAY, title="Garden Morning Song"):
    return videos.create(db, agent("production-manager"), channel, title)


def add_brief(db, agent, video, approve=True, **over):
    b = briefs.create(db, agent("creative-director"), video.id, brief_content(**over))
    if approve:
        briefs.review(db, agent("production-manager"), b.id, approve=True)
    return b


def add_lyrics(db, agent, video, text=LYRICS_A, kind="lyrics"):
    return scripts.add_script(db, agent("script-lyrics-writer"), video.id, kind=kind, text=text, author_kind="human",
                              author_label="test fixture")


def add_music(db, agent, video, *, seed=3, provider="local-procedural", vocals=False, license_type="owner-generated",
              commercial="yes", structure=("intro", "verse", "chorus", "outro"), **extra):
    comp = synth.compose({"tempo_bpm": 120, "key": "C major", "seed": seed, "structure": list(structure),
                          "bars": {"intro": 1, "verse": 2, "chorus": 2, "outro": 1}})
    out = get_settings().artifacts_dir / "videos" / str(video.id) / f"music-{seed}.wav"
    comp.write_wav(out)
    return assets.register(
        db, agent("original-music-specialist"), video_id=video.id, kind="music", role="soundtrack", path=out, provider=provider,
        license_type=license_type, license_ref="generated by this software from a seed; no third-party material" if commercial == "yes" else None,
        commercial_use=commercial, seed=seed, generation_ref=None if provider in assets.LOCAL_PROVIDERS else "gen-123",
        prompt=None if provider in assets.LOCAL_PROVIDERS else "gentle birthday tune", params={"vocals": vocals, **extra}), comp


def add_scenes(db, agent, video, *, base_seed=100, n=3, size=(320, 180)):
    out = []
    for i in range(n):
        p = get_settings().artifacts_dir / "videos" / str(video.id) / f"scene-{i}.png"
        imaging.make_scene(p, size=size, seed=base_seed + i * 17, title=f"Scene {i + 1}", motif="confetti" if i % 2 else "sun")
        out.append(assets.register(db, agent("image-generation-specialist"), video_id=video.id, kind="image", role=f"scene-{i}", path=p,
                                   provider="local-procedural", license_type="owner-generated", commercial_use="yes",
                                   license_ref="generated by this software from a seed", seed=base_seed + i * 17,
                                   params={"dhash": imaging.dhash(p)}))
    return out


def add_thumbnail(db, agent, video, *, seed=5, title="Garden Morning"):
    p = get_settings().artifacts_dir / "videos" / str(video.id) / "thumb.png"
    imaging.make_thumbnail(p, title=title, seed=seed, size=(640, 360))  # full 1280x720 is exercised in the QA tests
    return assets.register(db, agent("thumbnail-designer"), video_id=video.id, kind="thumbnail", role="thumbnail", path=p,
                           provider="local-procedural", license_type="owner-generated", commercial_use="yes",
                           license_ref="generated by this software from a seed", seed=seed, params={"dhash": imaging.dhash(p)})


def full_package(db, agent, video, *, lyrics=LYRICS_A, seed=3, scene_seed=100, thumb_seed=5, **brief_over):
    add_brief(db, agent, video, **brief_over)
    add_lyrics(db, agent, video, lyrics)
    add_music(db, agent, video, seed=seed)
    add_scenes(db, agent, video, base_seed=scene_seed)
    add_thumbnail(db, agent, video, seed=thumb_seed)


def tiny_mp4(path: Path, *, seconds=3, size="320x180", extra_v=None, extra_a=None, audio=True) -> Path:
    """A genuine small H.264/AAC file for tests that need a real video."""
    path.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", f"testsrc=size={size}:rate=30:duration={seconds}"]
    if audio:
        cmd += ["-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}"]
    vf = extra_v or "null"
    cmd += ["-vf", vf]
    if audio:
        cmd += ["-af", extra_a or "volume=-12dB"]
    cmd += ["-c:v", "libx264", "-pix_fmt", "yuv420p", "-r", "30"]
    if audio:
        cmd += ["-c:a", "aac", "-ar", "44100"]
    cmd += [str(path)]
    subprocess.run(cmd, check=True)
    return path


